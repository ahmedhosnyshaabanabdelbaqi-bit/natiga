export function localeMiddleware(request: Request, response: Response, next: NextFunction) {
  const locale = getLocale(request);
  response.locals.locale = locale;
  response.setHeader('Content-Language', locale);
  response.vary('Accept-Language');
  const sendJson = response.json.bind(response);
  response.json = ((body: unknown) => {
    if (Array.isArray(body) && request.path === '/api/audit' && response.statusCode < 400) {
      return sendJson(body.map(event => localizeAudit(event, locale)));
    }
    if (body && typeof body === 'object' && !Array.isArray(body)) {
      const object = body as Record<string, any>;
      if (response.statusCode >= 400 && typeof object.error === 'string') {
        return sendJson({ ...object, error: translateError(object.error, locale) });
      }
      if (response.statusCode < 400 && /^\/api\/patients\/[^/]+$/.test(request.path) && Array.isArray(object.events)) {
        return sendJson({ ...object, events: object.events.map((event: Record<string, any>) => localizeAudit(event, locale)) });
      }
      if (response.statusCode < 400 && request.path === '/api/dashboard' && Array.isArray(object.activity)) {
        return sendJson({ ...object, activity: object.activity.map((event: Record<string, any>) => localizeAudit(event, locale)) });
      }
      // These keys are fixed definitions produced by the report endpoint, never user records.
      if (request.path === '/api/reports' && response.statusCode < 400) {
        return sendJson({ ...object,
          period: object.period ? { ...object.period, from: systemText(locale, object.period.from) } : object.period,
          definitions: object.definitions ? Object.fromEntries(Object.entries(object.definitions).map(([key, value]) => [key, typeof value === 'string' ? systemText(locale, value) : value])) : object.definitions,
        });
      }
      if (response.statusCode < 400 && request.path.startsWith('/api/payroll/')) return sendJson(localizePayroll(object, locale));
      if (response.statusCode < 400 && request.path === '/api/attendance' && Array.isArray(object.periods)) {
        return sendJson({ ...object, periods: object.periods.map((period: Record<string, any>) => localizePayroll(period, locale)) });
      }
    }
    return sendJson(body);
  }) as Response['json'];
  next();
}

function localizePayroll(period: Record<string, any>, locale: Locale) {
  const issues = (values: unknown) => Array.isArray(values) ? values.map(issue => {
    if (!issue || typeof issue.message !== 'string') return issue;
    const unmapped = /^توجد (\d+) بصمة غير مربوطة بموظف$/.exec(issue.message);
    return { ...issue, message: locale === 'en' && unmapped ? `${unmapped[1]} attendance punches are not linked to an employee.` : systemText(locale, issue.message) };
  }) : values;
  return { ...period,
    ...(typeof period.basis === 'string' ? { basis: systemText(locale, period.basis) } : {}),
    ...(Array.isArray(period.issues) ? { issues: issues(period.issues) } : {}),
    ...(Array.isArray(period.employees) ? { employees: period.employees.map((employee: Record<string, any>) => ({ ...employee, issues: issues(employee.issues) })) } : {}),
  };
}
