export function systemText(locale: Locale, arabic: string): string {
  return locale === 'en' ? (englishSystemText[arabic] ?? arabic) : arabic;
}

export function getLocale(request: Request): Locale {
  if ((request.path.startsWith('/api/print/') || request.path === '/api/financial-statements') && (request.query.lang === 'en' || request.query.lang === 'ar')) return request.query.lang;
  const preferences = (request.get('accept-language') || '').split(',').map((part, order) => {
    const [language, ...parameters] = part.trim().toLowerCase().split(';');
    const q = parameters.find(parameter => parameter.trim().startsWith('q='));
    const quality = q === undefined ? 1 : Number(q.trim().slice(2));
    return { language: language.split('-')[0], quality, order };
  }).filter(item => Number.isFinite(item.quality) && item.quality > 0 && item.quality <= 1)
    .sort((a, b) => b.quality - a.quality || a.order - b.order);
  return preferences.find(item => item.language === 'en' || item.language === 'ar')?.language as Locale || 'ar';
}

export function translateError(message: string, locale: Locale): string {
  if (locale === 'ar') return message;
  if (englishSystemText[message]) return englishSystemText[message];
  const duplicate = /^يوجد ملف محتمل مكرر: (.+)\. راجع الهوية ثم أكد إضافة ملف مستقل$/.exec(message);
  if (duplicate) return `A possible duplicate record exists: ${duplicate[1]}. Review the identity before confirming a separate record.`;
  const csvRow = /^عدد أعمدة CSV غير صحيح في السطر (\d+)$/.exec(message);
  if (csvRow) return `The CSV column count is incorrect on row ${csvRow[1]}.`;
  const insufficientStock = /^رصيد (.+) غير كافٍ؛ حوّل العجز إلى طلب شراء$/.exec(message);
  if (insufficientStock) return `Insufficient ${insufficientStock[1]} stock. Convert the shortage to a purchase request.`;
  const labelText = (label: string) => englishSystemText[label] || (/^[a-zA-Z0-9_. -]+$/.test(label) ? label.replace(/_/g, ' ') : 'field');
  let match = /^يرجى إدخال (.+)$/.exec(message);
  if (match) return `Please enter ${labelText(match[1])}.`;
  match = /^قيمة (.+) غير صالحة$/.exec(message);
  if (match) return `The value for ${labelText(match[1])} is invalid.`;
  match = /^تاريخ (.+) غير صالح$/.exec(message);
  if (match) return `The date for ${labelText(match[1])} is invalid.`;
  match = /^(.+) غير صالح$/.exec(message);
  if (match) return `The ${labelText(match[1])} is invalid.`;
  return /[\u0600-\u06ff]/.test(message) ? 'The request could not be completed. Review the input and try again.' : message;
}

