const messages: Record<Lang, Record<MessageKey, string>> = { ar, en };

const STORAGE_KEY = 'erp.lang';

function readStoredLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'ar' || saved === 'en') return saved;
  } catch {
    // تخزين المتصفح قد يكون محجوبًا — العربية هي الافتراضي
  }
  return 'ar';
}

/** يطبّق اللغة والاتجاه على عنصر html — وهو ما يقلب موضع القائمة الجانبية. */
export function applyDirection(lang: Lang): void {
  const root = document.documentElement;
  root.setAttribute('lang', lang);
  root.setAttribute('dir', LANG_DIR[lang]);
}

interface I18nState {
  lang: Lang;
  dir: Dir;
  setLang: (lang: Lang) => void;
  toggle: () => void;
}

export const useI18nStore = create<I18nState>((set, get) => ({
  lang: readStoredLang(),
  dir: LANG_DIR[readStoredLang()],

  setLang: (lang) => {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // الاختيار يبقى لهذه الجلسة فقط إن تعذّر التخزين
    }
    applyDirection(lang);
    set({ lang, dir: LANG_DIR[lang] });
  },

  toggle: () => get().setLang(get().lang === 'ar' ? 'en' : 'ar'),
}));

/** ترجمة مفتاح مع استبدال المعاملات {name}. */
export function translate(lang: Lang, key: MessageKey, params?: Record<string, string | number>): string {
  let text: string = messages[lang][key] ?? messages.ar[key] ?? key;

  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }

  return text;
}

/** الاستخدام داخل المكوّنات: const { t, lang, dir, toggle } = useI18n(); */
export function useI18n() {
  const lang = useI18nStore((s) => s.lang);
  const dir = useI18nStore((s) => s.dir);
  const setLang = useI18nStore((s) => s.setLang);
  const toggle = useI18nStore((s) => s.toggle);

  // مرجع ثابت ما دامت اللغة ثابتة — وإلا تُعاد أي useEffect تعتمد عليه في كل رسم
  const t = useCallback(
    (key: MessageKey, params?: Record<string, string | number>) => translate(lang, key, params),
    [lang],
  );

  return { lang, dir, setLang, toggle, t };
}

/** للاستخدام خارج المكوّنات (دوال التنسيق مثلًا). */
export function currentLang(): Lang {
  return useI18nStore.getState().lang;
}

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  return translate(currentLang(), key, params);
}
